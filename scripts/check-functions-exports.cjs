#!/usr/bin/env node
/**
 * Cloud Functions export integrity check — fails CI when a function that
 * `functions/index.js` re-exports is not actually exported by its module.
 *
 * WHY: Firebase's source discovery only sees what `functions/index.js` exports.
 * If a re-exported name resolves to `undefined`, discovery silently omits that
 * function — while the deployed copy still exists in the project. Every full
 * `firebase deploy --only functions` then aborts with
 *
 *     The following functions are found in your project but do not exist in
 *     your local source code ... Aborting because deletion cannot proceed in
 *     non-interactive mode.
 *
 * and deploys NOTHING AT ALL. That is a repo-wide outage of the deploy path,
 * not a one-function problem: it happened in #699 (fixed in #912), where
 * `functions/src/scheduled/catalogAudit.js` attached two scheduled functions
 * as `exports.dailyCatalogAudit = ...` and then reassigned the whole module
 * object at the tail:
 *
 *     module.exports = { getDefaultAuditConfig, runProductAudit };  // clobber
 *
 * Reassigning `module.exports` REPLACES the object the earlier `exports.*`
 * assignments wrote to, discarding both scheduled functions. Full deploys were
 * broken for two weeks before anyone traced it.
 *
 * IMPORTANT — `firebase deploy --only functions --dry-run` does NOT catch this.
 * It reports "Dry run complete!" with the bug present, because it performs
 * source discovery but skips the prod-vs-local deletion comparison that is what
 * actually aborts. Do not use --dry-run as evidence that this class of bug is
 * resolved; this script is the check that can actually fail.
 *
 * HOW: static AST analysis — no credentials, no Firebase login, no
 * `functions/node_modules`, nothing executed. For each module it replays the
 * top-level export statements in source order to compute the names the module
 * really exports (`exports.X =` adds one; `module.exports = {...}` RESETS to
 * that object's keys), then:
 *
 *   CHECK 1 (root cause): flags any `module.exports = {...}` that drops names an
 *           earlier `exports.X =` had already attached.
 *   CHECK 2 (symptom):    flags any name `functions/index.js` destructures from
 *           a local `require(...)` and re-exports, that the target module does
 *           not export — whatever the cause.
 *   CHECK 3 (shadowing):  flags a name attached as a trigger
 *           (`exports.X = onCall(...)`) that a LATER top-level assignment
 *           re-points at something else — typically the plain helper of the
 *           same name exported at the tail for tests. The name still exists, so
 *           checks 1 and 2 both pass, but discovery finds a plain value and
 *           `firebase deploy` refuses the target with "No function matches the
 *           filter: default:X". Real: `closeStatementImport` in #1418, caught
 *           only by an actual deploy attempt. A `typeof x === 'function'` smoke
 *           test cannot catch it either, because the helper is a function.
 *
 * This deliberately uses a real parser (acorn) rather than regexes. An earlier
 * hand-rolled scanner produced false positives on ordinary code — comments
 * containing parentheses, `'https://'` in a string, and a regex literal whose
 * character class contained a quote (`/[..."'...]/`) each desynchronised it and
 * made real exports look missing. A gate that cries wolf gets switched off.
 *
 * Anything not statically resolvable (dynamic require path, `module.exports =`
 * some identifier, spread, or a file that fails to parse) is reported as
 * SKIPPED rather than silently passed, so the gate never quietly narrows its
 * coverage without saying so.
 *
 * Run: node scripts/check-functions-exports.cjs
 */

const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const ROOT = path.resolve(__dirname, '..');
const FUNCTIONS_DIR = path.join(ROOT, 'functions');
const INDEX_FILE = path.join(FUNCTIONS_DIR, 'index.js');

// `functions/vendor/` is a build artifact regenerated by the functions predeploy
// (see CLAUDE.md) — not hand-written source, so not ours to police.
const IGNORED_DIRS = new Set(['node_modules', 'vendor', 'lib', 'coverage']);

/** Recursively list .js files under functions/, skipping build output. */
function listFunctionFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED_DIRS.has(entry.name)) continue;
      out.push(...listFunctionFiles(full));
    } else if (entry.name.endsWith('.js')) {
      // Deliberately extension-exact: index.js.backup / .backup2 are dead copies.
      out.push(full);
    }
  }
  return out;
}

function parse(source) {
  return acorn.parse(source, {
    ecmaVersion: 'latest',
    sourceType: 'script',
    allowReturnOutsideFunction: true,
    locations: true,
  });
}

/** `a.b` (non-computed) -> "a.b"; anything else -> null. */
function memberPath(node) {
  if (!node || node.type !== 'MemberExpression' || node.computed) return null;
  const prop = node.property.type === 'Identifier' ? node.property.name : null;
  if (!prop) return null;
  if (node.object.type === 'Identifier') return `${node.object.name}.${prop}`;
  const inner = memberPath(node.object);
  return inner ? `${inner}.${prop}` : null;
}

/** Top-level (non-computed, non-spread) keys of an object literal. */
function objectKeys(node) {
  const keys = new Set();
  let complete = true;
  for (const prop of node.properties) {
    if (prop.type === 'SpreadElement') { complete = false; continue; }
    if (prop.computed) { complete = false; continue; }
    const k = prop.key;
    if (k.type === 'Identifier') keys.add(k.name);
    else if (k.type === 'Literal') keys.add(String(k.value));
    else complete = false;
  }
  return { keys, complete };
}

/**
 * Replay a module's top-level export statements in source order.
 * Returns { names:Set, clobbers:[{line, dropped:[]}], resolvable:boolean }.
 * `resolvable:false` means we hit a form we cannot model and must not draw
 * conclusions from.
 */
function analyzeModule(source) {
  let ast;
  try {
    ast = parse(source);
  } catch {
    return { names: new Set(), clobbers: [], resolvable: false, parseError: true };
  }

  let names = new Set();
  const clobbers = [];
  // Names attached as an actual Firebase trigger (`exports.X = onCall(...)`),
  // and any that a LATER assignment re-pointed at something else.
  const triggers = new Map(); // name -> line
  const shadowed = [];
  let resolvable = true;

  for (const stmt of ast.body) {
    if (stmt.type !== 'ExpressionStatement') continue;
    const expr = stmt.expression;

    // Object.assign(module.exports, ...) — can't model what it merges in.
    if (
      expr.type === 'CallExpression' &&
      memberPath(expr.callee) === 'Object.assign' &&
      expr.arguments.some((a) => memberPath(a) === 'module.exports')
    ) {
      resolvable = false;
      continue;
    }

    if (expr.type !== 'AssignmentExpression' || expr.operator !== '=') continue;
    const target = memberPath(expr.left);
    if (!target) continue;

    // exports.X = ...   /   module.exports.X = ...
    const propMatch = /^(?:exports|module\.exports)\.([A-Za-z0-9_$]+)$/.exec(target);
    if (propMatch) {
      const name = propMatch[1];
      const trigger = triggerFactory(expr.right);
      if (trigger) {
        triggers.set(name, { line: stmt.loc.start.line, factory: trigger });
      } else if (triggers.has(name)) {
        // CHECK 3: the name still EXISTS, so check 1 and check 2 both pass —
        // but it no longer points at the trigger, and Firebase's discovery
        // finds a plain value where a function should be. `firebase deploy`
        // then refuses the target with "No function matches the filter:
        // default:NAME", and a `typeof x === 'function'` smoke test cannot
        // tell the difference because the helper is a function too.
        shadowed.push({
          name,
          triggerLine: triggers.get(name).line,
          factory: triggers.get(name).factory,
          shadowLine: stmt.loc.start.line,
        });
      }
      names.add(name);
      continue;
    }

    if (target === 'module.exports') {
      if (expr.right.type !== 'ObjectExpression') {
        resolvable = false; // e.g. `module.exports = someIdentifier`
        continue;
      }
      const { keys, complete } = objectKeys(expr.right);
      if (!complete) resolvable = false;
      // THE BUG: this assignment replaces the exports object wholesale.
      const dropped = [...names].filter((n) => !keys.has(n));
      if (dropped.length) clobbers.push({ line: stmt.loc.start.line, dropped });
      names = keys;
    }
  }

  return { names, clobbers, shadowed, resolvable, parseError: false };
}

/**
 * The Firebase trigger factory an expression calls, if any.
 *
 * Only these produce a deployable endpoint; anything else assigned over one of
 * them silently un-deploys the function.
 */
const TRIGGER_FACTORIES = new Set([
  'onCall', 'onRequest', 'onSchedule', 'onTaskDispatched', 'onInit',
  'onDocumentWritten', 'onDocumentCreated', 'onDocumentUpdated', 'onDocumentDeleted',
  'onValueWritten', 'onValueCreated', 'onValueUpdated', 'onValueDeleted',
  'onObjectFinalized', 'onObjectDeleted', 'onObjectArchived', 'onObjectMetadataUpdated',
  'onMessagePublished', 'onCustomEventPublished',
  'beforeUserCreated', 'beforeUserSignedIn',
  'onUserCreated', 'onUserDeleted',
]);

function triggerFactory(node) {
  if (!node || node.type !== 'CallExpression') return null;
  const callee = node.callee;
  const name = callee.type === 'Identifier'
    ? callee.name
    : callee.type === 'MemberExpression' && callee.property.type === 'Identifier'
      ? callee.property.name
      : null;
  return name && TRIGGER_FACTORIES.has(name) ? name : null;
}

/**
 * Parse `functions/index.js` for local re-exports:
 *   const { a, b: c } = require('./src/x');
 *   exports.a = a;  exports.c = c;
 *
 * Note `const { a: b }` takes property `a` from the module and binds it to `b`.
 * The name to verify against the target module is the PROPERTY (`a`); checking
 * the local binding instead reports every aliased import as missing.
 */
function collectIndexReExports(source) {
  const ast = parse(source);
  const bindingOrigin = new Map(); // local binding -> { from, property }

  for (const stmt of ast.body) {
    if (stmt.type !== 'VariableDeclaration') continue;
    for (const decl of stmt.declarations) {
      if (!decl.init || decl.id.type !== 'ObjectPattern') continue;
      const init = decl.init;
      if (
        init.type !== 'CallExpression' ||
        init.callee.type !== 'Identifier' ||
        init.callee.name !== 'require' ||
        init.arguments.length !== 1 ||
        init.arguments[0].type !== 'Literal'
      ) continue;
      const from = String(init.arguments[0].value);
      if (!from.startsWith('.')) continue; // node_modules — not ours to verify

      for (const prop of decl.id.properties) {
        if (prop.type !== 'Property' || prop.computed) continue;
        if (prop.key.type !== 'Identifier') continue;
        if (prop.value.type !== 'Identifier') continue; // nested/default patterns
        bindingOrigin.set(prop.value.name, { from, property: prop.key.name });
      }
    }
  }

  const out = [];
  for (const stmt of ast.body) {
    if (stmt.type !== 'ExpressionStatement') continue;
    const expr = stmt.expression;
    if (expr.type !== 'AssignmentExpression' || expr.operator !== '=') continue;
    const target = memberPath(expr.left);
    const m = target && /^exports\.([A-Za-z0-9_$]+)$/.exec(target);
    if (!m) continue;
    if (expr.right.type !== 'Identifier') continue;
    const origin = bindingOrigin.get(expr.right.name);
    if (origin) {
      out.push({ name: m[1], property: origin.property, from: origin.from, line: stmt.loc.start.line });
    }
  }
  return out;
}

function resolveLocal(from) {
  const base = path.resolve(FUNCTIONS_DIR, from);
  for (const cand of [base, `${base}.js`, path.join(base, 'index.js')]) {
    if (fs.existsSync(cand) && fs.statSync(cand).isFile()) return cand;
  }
  return null;
}

function main() {
  if (!fs.existsSync(INDEX_FILE)) {
    console.error(`✗ Cloud Functions export check: ${path.relative(ROOT, INDEX_FILE)} not found.`);
    process.exit(1);
  }

  const failures = [];
  const skipped = [];

  const files = listFunctionFiles(FUNCTIONS_DIR);
  const cache = new Map();
  const analyze = (file) => {
    if (!cache.has(file)) cache.set(file, analyzeModule(fs.readFileSync(file, 'utf8')));
    return cache.get(file);
  };

  // ---- CHECK 1: module.exports clobbering earlier exports.X assignments -----
  // ---- CHECK 3: a later assignment re-pointing a trigger export ------------
  for (const file of files) {
    const { clobbers, shadowed, parseError } = analyze(file);
    if (parseError) {
      skipped.push(`${path.relative(ROOT, file)} — could not be parsed`);
      continue;
    }
    for (const { name, factory, triggerLine, shadowLine } of shadowed) {
      failures.push({
        file: path.relative(ROOT, file),
        line: shadowLine,
        detail:
          `\`${name}\` was attached as a ${factory}() trigger on line ${triggerLine}, then ` +
          `re-pointed at something else on line ${shadowLine}. The name still exists, so the ` +
          'clobber and re-export checks both pass — but discovery finds a plain value where the ' +
          'endpoint should be.',
        fix:
          `Export the helper under a different name (e.g. \`module.exports.run${name[0].toUpperCase()}${name.slice(1)}\`). ` +
          `\`firebase deploy\` fails this as "No function matches the filter: default:${name}", and a ` +
          '`typeof x === "function"` smoke test cannot catch it because the helper is a function too.',
      });
    }
    for (const { line, dropped } of clobbers) {
      failures.push({
        file: path.relative(ROOT, file),
        line,
        detail:
          '`module.exports = {...}` replaces the exports object, discarding ' +
          `${dropped.length} earlier \`exports.X =\` assignment(s): ${dropped.join(', ')}`,
        fix:
          `Assign onto \`exports\` instead (e.g. \`exports.${dropped[0]} = ${dropped[0]};\`). ` +
          'Do NOT just add the names to the object literal — they are properties, ' +
          `not bindings, so \`module.exports = { ${dropped[0]} }\` throws a ReferenceError.`,
      });
    }
  }

  // ---- CHECK 2: index.js re-exports a name its module does not export -------
  const reExports = collectIndexReExports(fs.readFileSync(INDEX_FILE, 'utf8'));
  let verified = 0;

  for (const { name, property, from, line } of reExports) {
    const target = resolveLocal(from);
    if (!target) {
      skipped.push(`${name} — could not resolve require('${from}')`);
      continue;
    }
    const { names, resolvable, parseError } = analyze(target);
    if (parseError) {
      skipped.push(`${name} — ${path.relative(ROOT, target)} could not be parsed`);
      continue;
    }
    if (!resolvable) {
      skipped.push(`${name} — ${path.relative(ROOT, target)} uses a dynamic export form`);
      continue;
    }
    verified++;
    if (!names.has(property)) {
      failures.push({
        file: 'functions/index.js',
        line,
        detail:
          `re-exports \`${name}\` from '${from}', but ` +
          `${path.relative(ROOT, target)} does not export \`${property}\` — it resolves to ` +
          'undefined, so Firebase discovery will not see this function',
        fix: `Export \`${property}\` from ${path.relative(ROOT, target)}, or drop the re-export from functions/index.js.`,
      });
    }
  }

  if (failures.length) {
    console.error(
      `\n✗ Cloud Functions export integrity: ${failures.length} problem(s) that can ABORT ` +
        'every full `firebase deploy --only functions`:\n'
    );
    for (const f of failures) {
      console.error(`   • ${f.file}${f.line ? `:${f.line}` : ''}`);
      console.error(`     ${f.detail}`);
      console.error(`     fix: ${f.fix}\n`);
    }
    console.error(
      'Note: `firebase deploy --only functions --dry-run` does NOT detect this — it skips\n' +
        'the prod-vs-local deletion comparison and reports success anyway. See #912.\n'
    );
    process.exit(1);
  }

  console.log(
    `✓ Cloud Functions export integrity: ${files.length} module(s) scanned, ` +
      `${verified} index.js re-export(s) resolved, no clobbered or undefined exports.`
  );
  if (skipped.length) {
    console.log(`  (${skipped.length} not statically resolvable, not verified:)`);
    for (const s of skipped) console.log(`   - ${s}`);
  }
}

if (require.main === module) main();

// Exported for targeted testing/debugging of the static analysis.
module.exports = { analyzeModule, collectIndexReExports };
