/** Delete a single file (storage + Firestore + mirrored deliverable if any) */
export async function deleteManagedFile(fileId: string): Promise<void> {
  const fileDoc = await getDoc(doc(db, FILES_COLLECTION, fileId));
  if (!fileDoc.exists()) return;

  const data = fileDoc.data() as ManagedFile & {
    _sourceId?: string;
    _sourceCollection?: string;
  };

  try {
    await deleteObject(ref(storage, data.storagePath));
  } catch {
    // Storage file may already be gone
  }

  // If this was mirrored from a deliverable, also delete the source deliverable
  if (data._sourceId && data._sourceCollection === 'deliverables' && data.projectId && data.itemId) {
    try {
      await deleteDoc(
        doc(db, 'designProjects', data.projectId, 'designItems', data.itemId, 'deliverables', data._sourceId)
      );
    } catch {
      // Source deliverable may already be gone
    }
  }

  await deleteDoc(doc(db, FILES_COLLECTION, fileId));
}

/** Bulk delete files */
export async function deleteManagedFiles(fileIds: string[]): Promise<{ deleted: number; failed: number }> {
  let deleted = 0;
  let failed = 0;
  for (const id of fileIds) {
    try {
      await deleteManagedFile(id);
      deleted++;
    } catch {
      failed++;
    }
  }
  return { deleted, failed };
}

