// Overwrite (destructive — same version, same document)
// ============================================

/**
 * Overwrite a file in place without creating a new version.
 *
 * Order of operations (upload-before-delete so a failed upload never destroys
 * the original):
 *   1. Upload new file to a fresh storage path.
 *   2. Update the Firestore doc to point at the new path.
 *   3. Delete the old storage object.
 *
 * If step 2 fails, we roll back the newly-uploaded storage object so the doc
 * still points at the original (which has NOT been deleted).
 */
export async function overwriteFile(
  existingFileId: string,
  newFile: File,
  newName?: string,
  uploadedBy?: string,
  uploadedByName?: string,
  allowApprovedOverride = false,
): Promise<ManagedFile> {
  const existingDoc = await getDoc(doc(db, FILES_COLLECTION, existingFileId));
  if (!existingDoc.exists()) throw new Error('File not found');

  const existing = { id: existingDoc.id, ...existingDoc.data() } as ManagedFile;
  const previousStoragePath = existing.storagePath;

  // Approval lock — see replaceFile docstring.
  if (existing.status === 'approved' && !allowApprovedOverride) {
    throw new Error(
      `File "${existing.name}" is marked approved. Mark it for review first, or request admin override before overwriting.`,
    );
  }

  // 1. Upload new file to fresh path FIRST.
  const timestamp = Date.now();
  const randomSuffix = Math.random().toString(36).slice(2, 8);
  const basenameSource = newName || existing.name || newFile.name;
  const sanitized = basenameSource.replace(/[^a-zA-Z0-9.-]/g, '_').substring(0, 150);
  const storagePath = `project-files/${existing.projectId}/${existing.category}/${timestamp}_${randomSuffix}_${sanitized}`;
  const storageRef = ref(storage, storagePath);

  const uploadTask = uploadBytesResumable(storageRef, newFile, {
    contentType: newFile.type,
  });
  await uploadTask;
  const storageUrl = await getDownloadURL(storageRef);

  const updates: Record<string, unknown> = {
    fileName: newFile.name,
    fileSize: newFile.size,
    mimeType: newFile.type || 'application/octet-stream',
    storagePath,
    storageUrl,
    updatedAt: serverTimestamp(),
  };
  if (newName) updates.name = newName;
  if (uploadedBy) updates.uploadedBy = uploadedBy;
  if (uploadedByName !== undefined) updates.uploadedByName = uploadedByName || null;

  // 2. Update the doc to point at the new storage object.
  try {
    await updateDoc(doc(db, FILES_COLLECTION, existingFileId), updates);
  } catch (err) {
    // Roll back the orphaned new upload — the original is still referenced by
    // the unchanged Firestore doc, so the file is intact.
    try { await deleteObject(storageRef); } catch { /* best effort */ }
    throw err;
  }

  // 3. Now that the doc points at the new path, delete the old storage object.
  //    A failure here is non-fatal — it just leaves an orphan, which a
  //    reconciliation job can sweep later.
  try { await deleteObject(ref(storage, previousStoragePath)); } catch { /* best effort */ }

  return {
    ...existing,
    ...updates,
    storageUrl,
    storagePath,
  } as ManagedFile;
}

