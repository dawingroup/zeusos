/**
 * Download multiple files as a ZIP archive.
 * Returns a report of how many succeeded / failed so the caller can surface
 * partial failure to the user (policy: bulk operations must never fail silently).
 */
export async function downloadFilesAsZip(
  files: ManagedFile[],
  zipName: string = 'project-files.zip'
): Promise<{ zipped: number; failed: string[] }> {
  const JSZip = (await import('jszip')).default;
  const zip = new JSZip();
  const failed: string[] = [];
  let zipped = 0;

  const fetchPromises = files.map(async (file) => {
    try {
      const response = await fetch(file.storageUrl);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const blob = await response.blob();
      // Prevent name collisions. Prefer the policy-compliant display name over
      // the raw storage basename so the ZIP contents match what users see in
      // the UI and what the Naming Policy v4 mandates.
      const folder = file.itemName || file.category;
      const entryName = file.name || file.fileName;
      zip.file(`${folder}/${entryName}`, blob);
      zipped++;
    } catch (err) {
      console.warn(`Failed to fetch file ${file.fileName}:`, err);
      failed.push(file.name || file.fileName);
    }
  });

  await Promise.all(fetchPromises);

  const content = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(content);
  const a = document.createElement('a');
  a.href = url;
  a.download = zipName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);

  return { zipped, failed };
}

