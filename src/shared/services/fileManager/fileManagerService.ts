/** Hard ceiling on how many latest files the subscription fetches in one shot. */
export const PROJECT_FILES_SUBSCRIPTION_CAP = 500;

/**
 * Subscription payload — files plus a truncation signal so the UI can warn
 * when a project has more latest files than we're willing to stream at once.
 */
export interface ProjectFilesSnapshot {
  files: ManagedFile[];
  /**
   * True when the server returned exactly `PROJECT_FILES_SUBSCRIPTION_CAP`
   * documents — there may be more that we are not showing. Mature projects
   * should switch to cursor pagination (Phase 2).
   */
  truncated: boolean;
}

/**
 * Subscribe to real-time file updates for a project.
 * Calls callback immediately with current data and on every change.
 * Returns an unsubscribe function.
 *
 * Emits {@link ProjectFilesSnapshot} (files + truncation signal) so the UI
 * can render a "showing 500 of N+ — some files hidden" warning when the cap
 * is hit rather than silently dropping the tail.
 */
export function subscribeToProjectFiles(
  projectId: string,
  filters: FileQueryFilters | undefined,
  callback: (snap: ProjectFilesSnapshot) => void,
): () => void {
  // Keep query constraints minimal to use the projectId+isLatest index (already built).
  // itemId/category filtering is done client-side to avoid requiring extra composite indexes
  // while they are still building after migration.
  const q = query(
    collection(db, FILES_COLLECTION),
    where('projectId', '==', projectId),
    where('isLatest', '==', true),
    limit(PROJECT_FILES_SUBSCRIPTION_CAP),
  );

  return onSnapshot(
    q,
    (snapshot) => {
      let files = snapshot.docs.map((d) => ({ id: d.id, ...d.data() } as ManagedFile));
      const truncated = snapshot.size >= PROJECT_FILES_SUBSCRIPTION_CAP;

      // Client-side filtering
      if (filters?.itemId) files = files.filter((f) => f.itemId === filters.itemId);
      if (filters?.category) files = files.filter((f) => f.category === filters.category);

      // Sort newest first
      files.sort((a, b) => (b.uploadedAt?.toMillis?.() || 0) - (a.uploadedAt?.toMillis?.() || 0));

      callback({ files, truncated });
    },
    (err) => {
      console.error('[subscribeToProjectFiles] Error:', err);
      callback({ files: [], truncated: false });
    },
  );
}

/** Get all latest files for a project, with optional filters */
export async function getProjectFiles(
  projectId: string,
  filters?: FileQueryFilters
): Promise<ManagedFile[]> {
  const constraints = [
    where('projectId', '==', projectId),
  ];

  // Default to latest only unless explicitly overridden
  if (filters?.isLatest !== false) {
    constraints.push(where('isLatest', '==', true));
  }

  if (filters?.category) {
    constraints.push(where('category', '==', filters.category));
  }
  if (filters?.module) {
    constraints.push(where('module', '==', filters.module));
  }
  if (filters?.itemId) {
    constraints.push(where('itemId', '==', filters.itemId));
  }
  if (filters?.isAutoGenerated !== undefined) {
    constraints.push(where('isAutoGenerated', '==', filters.isAutoGenerated));
  }

  const q = query(collection(db, FILES_COLLECTION), ...constraints);
  const snapshot = await getDocs(q);

  return snapshot.docs
    .map((d) => ({ id: d.id, ...d.data() } as ManagedFile))
    .sort((a, b) => {
      const aTime = a.uploadedAt?.toMillis?.() || 0;
      const bTime = b.uploadedAt?.toMillis?.() || 0;
      return bTime - aTime;
    });
}

/** Get version history for a file (walk previousVersionId chain) */
export async function getFileVersions(fileId: string): Promise<ManagedFile[]> {
  const versions: ManagedFile[] = [];

  // First get the latest version in this chain
  const startDoc = await getDoc(doc(db, FILES_COLLECTION, fileId));
  if (!startDoc.exists()) return [];

  const startFile = { id: startDoc.id, ...startDoc.data() } as ManagedFile;
  versions.push(startFile);

  // Walk backwards through previousVersionId
  let currentId = startFile.previousVersionId;
  while (currentId) {
    const prevDoc = await getDoc(doc(db, FILES_COLLECTION, currentId));
    if (!prevDoc.exists()) break;
    const prevFile = { id: prevDoc.id, ...prevDoc.data() } as ManagedFile;
    versions.push(prevFile);
    currentId = prevFile.previousVersionId;
  }

  // Also find any newer versions that point to this file
  const newerQ = query(
    collection(db, FILES_COLLECTION),
    where('previousVersionId', '==', fileId)
  );
  const newerSnap = await getDocs(newerQ);
  for (const d of newerSnap.docs) {
    const f = { id: d.id, ...d.data() } as ManagedFile;
    if (!versions.find((v) => v.id === f.id)) {
      versions.push(f);
    }
  }

  // Sort by version descending
  return versions.sort((a, b) => b.version - a.version);
}

