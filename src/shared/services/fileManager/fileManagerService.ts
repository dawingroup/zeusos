/** Update a file's approval status */
export async function updateFileStatus(
  fileId: string,
  status: 'draft' | 'review' | 'approved' | 'superseded',
  userId?: string
): Promise<void> {
  const updates: Record<string, unknown> = {
    status,
    updatedAt: serverTimestamp(),
  };
  if (status === 'approved' && userId) {
    updates.approvedBy = userId;
    updates.approvedAt = serverTimestamp();
  }
  await updateDoc(doc(db, FILES_COLLECTION, fileId), updates);
}

/** Toggle portal sharing for a file */
export async function togglePortalSharing(
  fileId: string,
  share: boolean,
  userId: string,
  portalDisplayName?: string
): Promise<void> {
  const updates: Record<string, unknown> = {
    sharedToPortal: share,
    updatedAt: serverTimestamp(),
  };
  if (share) {
    updates.sharedToPortalAt = serverTimestamp();
    updates.sharedToPortalBy = userId;
    if (portalDisplayName) updates.portalDisplayName = portalDisplayName;
  }
  await updateDoc(doc(db, FILES_COLLECTION, fileId), updates);
}

