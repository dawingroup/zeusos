/**
 * Upload a file and create Firestore metadata doc
 */
export function uploadManagedFile(
  file: File,
  context: FileUploadContext,
  onProgress?: (progress: FileUploadProgress) => void
): { promise: Promise<ManagedFile>; abort: () => void } {
  // Naming Policy v4 — mandatory naming enforcement.
  //
  // When both `projectCode` and `policyName` are supplied, the storage
  // basename is the policy-compliant name so every download URL, bulk-ZIP
  // entry, and cross-system reference agrees with the display `name`.
  // When a policy name can't be constructed (no projectCode at callsite),
  // we fall back to the raw filename and log a warning — caller-driven
  // rejection is deferred to Phase 2 once every caller threads projectCode.
  if (!context.projectCode) {
    // eslint-disable-next-line no-console -- intentional until Phase 2 tightens this to a reject
    console.warn(
      `[uploadManagedFile] Upload of "${file.name}" missing projectCode — Naming Policy v4 cannot be enforced. ` +
        `Caller: module=${context.module} category=${context.category}`,
    );
  }
  const basenameSource = context.policyName || file.name;
  const sanitized = basenameSource.replace(/[^a-zA-Z0-9.-]/g, '_').substring(0, 150);
  // Timestamp + short random suffix prevents collisions when two users upload
  // the same filename within the same millisecond (possible during bulk imports
  // or parallel Workshop Viewer print-package pushes).
  const randomSuffix = Math.random().toString(36).slice(2, 8);
  const timestamp = Date.now();
  const storagePath = `project-files/${context.projectId}/${context.category}/${timestamp}_${randomSuffix}_${sanitized}`;
  const storageRef = ref(storage, storagePath);

  const uploadTask = uploadBytesResumable(storageRef, file, {
    contentType: file.type,
    customMetadata: {
      projectId: context.projectId,
      category: context.category,
      module: context.module,
      ...(context.itemId ? { itemId: context.itemId } : {}),
    },
  });

  const promise = new Promise<ManagedFile>((resolve, reject) => {
    uploadTask.on(
      'state_changed',
      (snapshot) => {
        onProgress?.({
          bytesTransferred: snapshot.bytesTransferred,
          totalBytes: snapshot.totalBytes,
          percentage: (snapshot.bytesTransferred / snapshot.totalBytes) * 100,
          state: snapshot.state as FileUploadProgress['state'],
        });
      },
      (error) => reject(error),
      async () => {
        try {
          const storageUrl = await getDownloadURL(uploadTask.snapshot.ref);
          const normalizedDeliverableType =
            context.deliverableType
            || (context.category === 'cad-model' ? '3d-model' : null);

          const fileDoc = {
            name: context.policyName || (normalizedDeliverableType
              ? `${normalizedDeliverableType} - ${file.name}`
              : file.name),
            fileName: file.name,
            fileSize: file.size,
            mimeType: file.type || 'application/octet-stream',
            storagePath,
            storageUrl,
            projectId: context.projectId,
            projectCode: context.projectCode || null,
            itemId: context.itemId || null,
            itemName: context.itemName || null,
            manufacturingOrderId: context.manufacturingOrderId || null,
            module: context.module,
            category: context.category,
            deliverableType: normalizedDeliverableType,
            version: 1,
            previousVersionId: null,
            isLatest: true,
            isAutoGenerated: context.isAutoGenerated || false,
            autoGenSource: context.autoGenSource || null,
            autoGenHash: context.autoGenHash || null,
            uploadedAt: serverTimestamp(),
            uploadedBy: context.uploadedBy || '',
            uploadedByName: context.uploadedByName || null,
            updatedAt: serverTimestamp(),
            tags: context.tags || [],
          };

          const docRef = await addDoc(collection(db, FILES_COLLECTION), fileDoc);
          const saved = await getDoc(docRef);

          // RAG auto-update hook removed in Phase 1.C (design-manager deleted).
          // TODO Phase 3: re-wire to `@/modules/campaigns/services/ragAutoUpdateService`
          // once Campaigns module is built — Campaign deliverable uploads should
          // similarly nudge RAG state.
          void normalizedDeliverableType;

          resolve({
            id: docRef.id,
            ...fileDoc,
            uploadedAt: saved.data()?.uploadedAt || ({} as Timestamp),
            updatedAt: saved.data()?.updatedAt || ({} as Timestamp),
          } as unknown as ManagedFile);
        } catch (error) {
          reject(error);
        }
      }
    );
  });

  return {
    promise,
    abort: () => uploadTask.cancel(),
  };
}

// ============================================
// Replace (versioning)
// ============================================

/**
 * Replace a file with a new version.
 * - Manual files: archives old version, creates new doc with version+1
 * - Auto-generated files: overwrites in place
 *
 * Approval lock (F-E2): rejects when the existing file is marked `approved`
 * unless `allowApprovedOverride` is explicitly true. The Firestore rules
 * mirror this gate for admin-only override — pass `allowApprovedOverride`
 * only after the caller has obtained admin confirmation from the UI.
 */
export async function replaceFile(
  existingFileId: string,
  newFile: File,
  uploadedBy: string,
  uploadedByName?: string,
  allowApprovedOverride = false,
): Promise<ManagedFile> {
  const existingDoc = await getDoc(doc(db, FILES_COLLECTION, existingFileId));
  if (!existingDoc.exists()) throw new Error('File not found');

  const existing = { id: existingDoc.id, ...existingDoc.data() } as ManagedFile;

  if (existing.status === 'approved' && !allowApprovedOverride) {
    throw new Error(
      `File "${existing.name}" is marked approved. Mark it for review first, or request admin override before replacing.`,
    );
  }

  if (existing.isAutoGenerated) {
    // Auto-gen: delete old storage, upload new in same path
    try { await deleteObject(ref(storage, existing.storagePath)); } catch { /* ok */ }

    const storageRef = ref(storage, existing.storagePath);
    const uploadTask = uploadBytesResumable(storageRef, newFile, {
      contentType: newFile.type,
    });
    await uploadTask;
    const newUrl = await getDownloadURL(storageRef);

    await updateDoc(doc(db, FILES_COLLECTION, existingFileId), {
      storageUrl: newUrl,
      fileSize: newFile.size,
      mimeType: newFile.type,
      fileName: newFile.name,
      updatedAt: serverTimestamp(),
      uploadedBy,
      uploadedByName: uploadedByName || null,
    });

    return { ...existing, storageUrl: newUrl, fileSize: newFile.size, fileName: newFile.name };
  }

  // Manual file: archive old, create new version.
  //
  // Atomicity: upload storage first (side-effectful but recoverable on retry),
  // then atomically flip `isLatest` on the old doc and create the new doc in a
  // single `writeBatch`. If the Storage upload fails, the previous version
  // remains the latest — no inconsistent state. If the batch fails, we clean
  // up the orphaned Storage object so repeat attempts don't accumulate junk.
  //
  // Storage basename reuses the existing file's policy-compliant display
  // `name` so every version in the chain presents consistently.
  const timestamp = Date.now();
  const randomSuffix = Math.random().toString(36).slice(2, 8);
  const basenameSource = existing.name || newFile.name;
  const sanitized = basenameSource.replace(/[^a-zA-Z0-9.-]/g, '_').substring(0, 150);
  const storagePath = `project-files/${existing.projectId}/${existing.category}/${timestamp}_${randomSuffix}_${sanitized}`;
  const storageRef = ref(storage, storagePath);

  const uploadTask = uploadBytesResumable(storageRef, newFile, {
    contentType: newFile.type,
  });
  await uploadTask;
  const storageUrl = await getDownloadURL(storageRef);

  const newVersion = existing.version + 1;
  const newDocRef = doc(collection(db, FILES_COLLECTION));
  const newDoc = {
    name: existing.name,
    fileName: newFile.name,
    fileSize: newFile.size,
    mimeType: newFile.type || 'application/octet-stream',
    storagePath,
    storageUrl,
    projectId: existing.projectId,
    projectCode: existing.projectCode || null,
    itemId: existing.itemId || null,
    itemName: existing.itemName || null,
    manufacturingOrderId: existing.manufacturingOrderId || null,
    module: existing.module,
    category: existing.category,
    deliverableType: existing.deliverableType || null,
    version: newVersion,
    previousVersionId: existingFileId,
    isLatest: true,
    isAutoGenerated: false,
    autoGenSource: null,
    autoGenHash: null,
    uploadedAt: serverTimestamp(),
    uploadedBy,
    uploadedByName: uploadedByName || null,
    updatedAt: serverTimestamp(),
    tags: existing.tags || [],
  };

  try {
    const batch = writeBatch(db);
    batch.update(doc(db, FILES_COLLECTION, existingFileId), {
      isLatest: false,
      updatedAt: serverTimestamp(),
    });
    batch.set(newDocRef, newDoc);
    await batch.commit();
  } catch (err) {
    // Firestore commit failed — roll back the orphaned Storage upload so a
    // retry starts clean and we don't leak storage objects with no metadata.
    try { await deleteObject(storageRef); } catch { /* best effort */ }
    throw err;
  }

  const saved = await getDoc(newDocRef);

  return {
    id: newDocRef.id,
    ...newDoc,
    uploadedAt: saved.data()?.uploadedAt || ({} as Timestamp),
    updatedAt: saved.data()?.updatedAt || ({} as Timestamp),
  } as unknown as ManagedFile;
}

