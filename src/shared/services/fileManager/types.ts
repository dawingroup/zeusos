/**
 * Extensions the Workshop Viewer can open. Source of truth for
 * - extension-based category classification ({@link getCategoryFromFileName}),
 * - the File Manager's "Process in Workshop" row action predicate,
 * - the Workshop Viewer's file-type accept filters.
 *
 * Keep this list in sync with the model parser's supported formats
 * (`src/subsidiaries/finishes/design-studio/services/modelParser`).
 */
export const CAD_MODEL_EXTENSIONS: ReadonlyArray<string> = [
  '3ds', 'dxf', 'obj', 'fbx', 'glb', 'gltf', 'stl',
];

/** Case-insensitive test for "is this filename a CAD model file?" */
export function isCadModelFileName(fileName: string | null | undefined): boolean {
  if (!fileName) return false;
  const ext = fileName.split('.').pop()?.toLowerCase();
  return !!ext && CAD_MODEL_EXTENSIONS.includes(ext);
}

/**
 * Best-guess {@link FileCategory} from a filename. Returns `null` when
 * the file doesn't clearly belong to a category — callers decide the
 * default (usually `'deliverable'`) in that case. This is intentionally
 * narrow: it only fires on extensions we have strong opinions about
 * (CAD models), so it doesn't accidentally re-route a PDF spec sheet
 * that happened to be named `something.pdf.obj.pdf`.
 */
export function getCategoryFromFileName(
  fileName: string | null | undefined,
): FileCategory | null {
  if (isCadModelFileName(fileName)) return 'cad-model';
  return null;
}

/** Format file size for display */
export function formatFileSize(bytes: number): string {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${parseFloat((bytes / Math.pow(k, i)).toFixed(1))} ${sizes[i]}`;
}

/**
 * Get file icon type.
 *
 * Prefer the filename when available because CAD formats (.3ds, .dxf,
 * .obj, .fbx) ship with `application/octet-stream` on most browsers —
 * the old MIME-only check was returning 'model' for every arbitrary
 * binary blob, which is both over- and under-inclusive.
 */
export function getFileIconType(
  mimeType: string | null | undefined,
  fileName?: string | null,
): 'image' | 'pdf' | 'spreadsheet' | 'model' | 'document' | 'other' {
  // Filename-based CAD detection wins over MIME because browsers lie.
  if (fileName && isCadModelFileName(fileName)) return 'model';

  if (!mimeType) return 'other';
  if (mimeType.startsWith('image/')) return 'image';
  if (mimeType === 'application/pdf') return 'pdf';
  if (mimeType.includes('spreadsheet') || mimeType === 'text/csv') return 'spreadsheet';
  if (mimeType.includes('model')) return 'model';
  if (mimeType.includes('document') || mimeType.includes('word')) return 'document';
  return 'other';
}
