/**
 * Unified File Manager Types
 * Shared type definitions for cross-module file management
 */

import type { Timestamp } from 'firebase/firestore';

/** File categories across modules */
export type FileCategory =
  | 'deliverable'
  | 'client-document'
  | 'production-doc'
  | 'report'
  // P21.3 — unified CAD handling. Workshop Viewer uploads (3ds/dxf/obj/
  // fbx/glb/stl) go here, which lets the File Manager list them alongside
  // deliverables + offer "Open in Studio" on rows instead of hiding 3D
  // assets behind the bespoke `workshop-viewer/{ts}/` storage path.
  | 'cad-model';

/** Source module for the file */
export type FileModule = 'design-manager' | 'manufacturing' | 'shared';

/**
 * Managed file — single Firestore document in `projectFiles` collection
 */
export interface ManagedFile {
  id: string;
  name: string;
  fileName: string;
  fileSize: number;
  mimeType: string;
  storagePath: string;
  storageUrl: string;

  // Context
  projectId: string;
  /**
   * Human-readable, policy-compliant project code — e.g. `DF-2025-001`.
   * Denormalised onto every file doc so Drive mirroring, naming enforcement,
   * and cross-system (Notion/Drive) joins can use the canonical policy key
   * instead of the opaque Firestore `projectId`. See Naming Policy v4.
   */
  projectCode?: string;
  itemId?: string;
  itemName?: string;
  manufacturingOrderId?: string;
  module: FileModule;
  category: FileCategory;
  deliverableType?: string; // e.g. 'cut-list', 'bom', 'shop-drawing'

  // Versioning
  version: number;
  previousVersionId?: string;
  isLatest: boolean;

  // Auto-generation
  isAutoGenerated: boolean;
  autoGenSource?: string;
  autoGenHash?: string;

  // Approval / status
  status?: 'draft' | 'review' | 'approved' | 'superseded';
  coversTypes?: string[];          // multi-type coverage (e.g. one drawing satisfies shop-drawing + spec)

  // Portal sharing
  sharedToPortal?: boolean;
  sharedToPortalAt?: Timestamp;
  sharedToPortalBy?: string;
  portalDisplayName?: string;

  // Drive mirror (Phase 2 — Shared Drive Architecture v3 §01_Active-Projects/{01..07})
  /** Google Drive file ID of the mirrored copy. Null until the mirror trigger writes it. */
  driveFileId?: string | null;
  /** `webViewLink` from the Drive API — "Open in Drive" anchor target. */
  driveWebViewLink?: string | null;
  /** Which `01..07` subfolder under the project folder this file was routed to. */
  driveFolderSubpath?: string | null;
  /** Server timestamp of the successful mirror write. */
  driveSyncedAt?: Timestamp | null;
  /** Last error from the mirror CF, if any. Cleared on next successful sync. */
  driveSyncError?: string | null;

  // Archive lifecycle (Phase 4 — Shared Drive Architecture v3 §02_Archive/{Year})
  /**
   * True when the parent project has been archived. Flipped by the
   * `archiveProject` Cloud Function; UI hides archived files by default
   * and surfaces them behind an explicit "show archived" toggle.
   */
  archived?: boolean;
  /** Server timestamp set by the archive CF on successful flag-write. */
  archivedAt?: Timestamp | null;
  /** Auth UID (or `system` for the scheduled sweep) that archived it. */
  archivedBy?: string | null;

  // Metadata
  uploadedAt: Timestamp;
  uploadedBy: string;
  uploadedByName?: string;
  updatedAt: Timestamp;
  tags?: string[];
}

