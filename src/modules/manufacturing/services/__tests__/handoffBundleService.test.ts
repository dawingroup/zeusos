// Minimal jszip mock — returns an object with `.file(path, blob)` recorder
// and a `.generateAsync()` that yields a deterministic stub Blob.
vi.mock('jszip', () => {
  return {
    default: class {
      files: Array<{ path: string; blob: Blob | string }> = [];
      file(path: string, blob: Blob | string) {
        this.files.push({ path, blob });
      }
      generateAsync(_opts: unknown) {
        return Promise.resolve(new Blob([`zip:${this.files.length}`], { type: 'application/zip' }));
      }
    },
  };
});

