/**
 * Phase 3 — tests for the handoff bundle service.
 *
 * Covers the behaviour contracts the audit's Phase 3 verification step
 * calls out:
 *   - zero-input → throws a clear error (nothing to hand off)
 *   - deterministic content hash
 *   - idempotent reuse on identical hash (second call returns the same bundle)
 *   - previous handoff-bundle docs are excluded from re-bundling
 *   - constituent files are flipped to `status='approved'` (the freeze)
 *   - bundle is auto-shared to the portal
 *   - `linkBundleToMO` writes `handoffBundleFileId` + `projectFileIds` onto the MO
 */
import { describe, it, expect, vi, beforeEach } from 'vitest';
import type { ManagedFile } from '@/shared/services/fileManager';

